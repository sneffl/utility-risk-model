## Markov transition-probability functions of "stress index" = bill/income.
## STATED MODELING ASSUMPTIONS -- see report Section 6. Not fit to any
## real transition dataset; no such public dataset exists.
cure_from_late       <- function(s) pmax(0.05, pmin(0.85, 0.75 - 1.6 * s))
progress_from_late   <- function(s) pmax(0.03, pmin(0.90, 0.08 + 1.6 * s))
cure_from_severe     <- function(s) pmax(0.02, pmin(0.60, 0.42 - 1.3 * s))
progress_from_severe <- function(s) pmax(0.02, pmin(0.70, 0.06 + 1.1 * s))
STATES <- c("Current", "Late", "Severe", "Disconnected")

build_transition_matrix <- function(tier, stress_index) {
  a  <- TIER_BASE_SLIP[[tier]]
  cL <- cure_from_late(stress_index);    pL <- progress_from_late(stress_index);    sL <- 1 - cL - pL
  cS <- cure_from_severe(stress_index);  pS <- progress_from_severe(stress_index);  sS <- 1 - cS - pS
  P <- matrix(0, 4, 4, dimnames = list(STATES, STATES))
  P["Current","Current"] <- 1 - a;  P["Current","Late"] <- a
  P["Late","Current"] <- cL;        P["Late","Late"] <- sL;       P["Late","Severe"] <- pL
  P["Severe","Current"] <- cS;      P["Severe","Severe"] <- sS;   P["Severe","Disconnected"] <- pS
  P["Disconnected","Disconnected"] <- 1
  P
}

analyze_chain <- function(P, horizon = 24) {
  transient <- STATES[STATES != "Disconnected"]
  Q <- P[transient, transient]
  N <- solve(diag(nrow(Q)) - Q)
  expected_steps <- N %*% matrix(1, nrow = nrow(Q)); rownames(expected_steps) <- transient
  x0 <- setNames(c(1, 0, 0, 0), STATES)
  traj <- matrix(0, horizon + 1, 4, dimnames = list(0:horizon, STATES)); traj[1, ] <- x0
  for (m in seq_len(horizon)) traj[m + 1, ] <- traj[m, ] %*% P
  list(expected_months = expected_steps["Current", 1], trajectory = traj,
       p6 = traj["6", "Disconnected"], p12 = traj["12", "Disconnected"])
}

## Real Experian Q1 2026 average auto-loan APR by credit tier
## (Experian "Average Car Loan Interest Rates by Credit Score").
CREDIT_TIERS <- data.frame(
  tier      = c("Super Prime", "Prime", "Near Prime", "Subprime", "Deep Subprime"),
  min_score = c(781, 661, 601, 501, 300),
  max_score = c(850, 780, 660, 600, 500),
  new_apr   = c(4.55, 6.23, 9.67, 13.44, 16.01),
  used_apr  = c(6.30, 8.77, 14.03, 19.42, 21.77)
)
score_to_tier <- function(score) {
  score <- max(300, min(850, score))
  CREDIT_TIERS[score >= CREDIT_TIERS$min_score & score <= CREDIT_TIERS$max_score, ][1, ]
}
## Commonly-cited (industry-estimate, NOT official FICO methodology)
## collection-impact ranges: bigger hit for higher starting scores.
collection_point_drop_range <- function(score) {
  if (score > 720) c(30, 50) else if (score >= 660) c(60, 80) else c(90, 110)
}
monthly_payment <- function(principal, annual_rate_pct, term_months) {
  r <- annual_rate_pct / 100 / 12
  if (r == 0) return(principal / term_months)
  principal * r * (1 + r)^term_months / ((1 + r)^term_months - 1)
}

