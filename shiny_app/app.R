## Shared paper styling for every plotly chart
chart_layout <- function(p, k = PALETTES$light, xaxis = list(), yaxis = list(), ...) {
  layout(p,
    paper_bgcolor = "rgba(0,0,0,0)", plot_bgcolor = "rgba(0,0,0,0)",
    font = list(color = k$ink, family = "Atkinson Next, system-ui, sans-serif", size = 13),
    hoverlabel = list(bgcolor = k$hover_bg, bordercolor = k$rule,
                      font = list(color = k$ink, family = "Atkinson Next, system-ui, sans-serif")),
    xaxis = modifyList(list(gridcolor = k$grid, zerolinecolor = k$rule, linecolor = k$dim), xaxis),
    yaxis = modifyList(list(gridcolor = k$grid, zerolinecolor = k$rule), yaxis),
    ...) |>
    config(displayModeBar = FALSE)
}

