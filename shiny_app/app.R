## Page switching and the dark mode switch. Dark mode starts on whatever
## the visitor picked last time, or their device setting, and the charts
## follow it through input$mode.
MASTHEAD_JS <- "
(function () {
  function stored() { try { return localStorage.getItem('bob-mode'); } catch (e) { return null; } }
  function save(m) { try { localStorage.setItem('bob-mode', m); } catch (e) {} }
  var dark = window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches;
  var start = stored() || (dark ? 'dark' : 'light');
  document.documentElement.setAttribute('data-bs-theme', start);

  function apply(m) {
    document.documentElement.setAttribute('data-bs-theme', m);
    var s = document.getElementById('mode-switch');
    if (s) s.setAttribute('aria-checked', m === 'dark' ? 'true' : 'false');
    if (window.Shiny && Shiny.setInputValue) Shiny.setInputValue('mode', m);
  }
  function markCurrent(v) {
    document.querySelectorAll('.masthead .go[data-go]').forEach(function (el) {
      var on = el.getAttribute('data-go') === v;
      el.classList.toggle('is-current', on);
      if (on && el.classList.contains('nav-step')) el.setAttribute('aria-current', 'page');
      else el.removeAttribute('aria-current');
    });
  }

  document.addEventListener('DOMContentLoaded', function () {
    apply(start);
    markCurrent('bill');
    document.addEventListener('click', function (e) {
      var go = e.target.closest('.go');
      if (go && window.Shiny) {
        Shiny.setInputValue('go', go.getAttribute('data-go'), { priority: 'event' });
        window.scrollTo(0, 0);
      }
      if (e.target.closest('#mode-switch')) {
        var m = document.documentElement.getAttribute('data-bs-theme') === 'dark' ? 'light' : 'dark';
        save(m); apply(m);
      }
    });
    window.jQuery(document).on('shiny:connected', function () {
      Shiny.setInputValue('mode', document.documentElement.getAttribute('data-bs-theme'));
      Shiny.addCustomMessageHandler('currentPage', markCurrent);
    });
  });
})();
"

