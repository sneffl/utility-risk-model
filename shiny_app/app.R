## ---------------------------------------------------------------
## Server
## ---------------------------------------------------------------
server <- function(input, output, session) {

  ## Chart colors follow the light/dark switch
  pc <- reactive(PALETTES[[if (identical(input$mode, "dark")) "dark" else "light"]])

  ## ---- Welcome, once per visit ----
  showModal(modalDialog(
    title = "Behind on the Bill",
    p("This site figures out what your electric bill should look like using NOAA weather records for your state, and shows what really happens if one goes unpaid, with the rules and help for all 50 states and DC."),
    p("Put your last bill in the first sentence on the next page and everything changes to match your home."),
    footer = div(class = "welcome-actions",
      tags$button(type = "button", class = "btn btn-primary btn-lg", `data-dismiss` = "modal", `data-bs-dismiss` = "modal", "Show me my bill"),
      actionButton("welcome_help", "My power is about to be shut off", class = "btn-outline-danger btn-lg")
    ),
    easyClose = TRUE
  ))
  observeEvent(input$welcome_help, {
    removeModal()
    nav_select("nav", "help")
  })

  ## Urgent-risk banner button
  observeEvent(input$goto_help, { nav_select("nav", "help") })

  ## Masthead clicks switch pages, and the masthead marks where you are
  observeEvent(input$go, { nav_select("nav", input$go) })
  observe({ session$sendCustomMessage("currentPage", if (is.null(input$nav)) "bill" else input$nav) })

  ## ---- Bill Forecast tab ----
  shock <- reactiveValues(active = FALSE, month = NULL, delta_temp = 0, days = 0, kind = "")

  ## Outside factors: local electricity price (state average) and how the
  ## home is heated. Gas/oil heat means winter heating never touches the
  ## electric bill, so that whole component drops out.
  heat_on <- reactive({ !identical(input$heat_fuel, "other") })
  price_factor <- reactive({
    pr <- STATE_PRICES$price[STATE_PRICES$state == input$state]
    if (length(pr) == 0) 1 else pr / NY_PRICE * STATE_SCALE[[input$state]]
  })

  ## Model-household dollars per month under the current fuel + state,
  ## before personal scaling. The bill model is linear in degree-days, so
  ## dropping the heating component is exact; the 80% band is rescaled in
  ## proportion to each month's remaining bill.
  sclim <- reactive(state_climate(input$state))
  srow  <- reactive(st_row(input$state))
  model_dollars <- reactive({
    cl <- sclim()
    heat <- if (heat_on()) HEATING_RATE_PER_HDD * cl$hdd else 0
    base <- BASELOAD + heat + COOLING_RATE_PER_CDD * cl$cdd
    ## The 8-in-10-years band keeps New York's year to year swing for each
    ## month, as a share of that month's bill
    data.frame(month = HIST_MONTHLY$month,
               bill = base * price_factor(),
               p10  = base * BAND_LO * price_factor(),
               p90  = base * BAND_HI * price_factor(),
               HDD = cl$hdd, CDD = cl$cdd,
               mean_temp = cl$mean_temp)
  })

  output$state_note <- renderUI({
    if (identical(input$state, "New York")) return(NULL)
    pr <- STATE_PRICES$price[STATE_PRICES$state == input$state]
    div(class = "note",
        sprintf("Priced at %s's average residential rate, %.1f cents/kWh (EIA, May 2026), with NOAA's 30-year weather normals for %s, and its typical year matched to EIA's 2024 average bill for the state. The 8-in-10-years range borrows New York's year to year swings, since that's the long record built into the site.",
                input$state, pr, srow()$city))
  })

  ## Personal calibration: if the visitor enters their own last bill, the
  ## ratio of their bill to the adjusted model bill for that month rescales
  ## every dollar in the app. Clamped so one odd bill can't produce a
  ## nonsense forecast.
  personal_factor <- reactive({
    b <- input$my_bill
    if (is.null(b) || is.na(b) || b <= 0) return(1)
    ref <- model_dollars()$bill[match(input$my_bill_month, month.abb)]
    max(0.25, min(5, b / ref))
  })
  output$calib_note <- renderUI({
    f <- personal_factor()
    if (identical(f, 1)) return(NULL)
    pct <- round(100 * abs(f - 1))
    dir <- if (f >= 1) "above" else "below"
    div(class = "note",
        sprintf("Calibrated to your bill: your household runs about %d%% %s the model home for your state and heating type, and every number in the app now reflects that.", pct, dir))
  })

  ## The month's climate, scaled to the visitor's household.
  climate_df <- reactive({
    md <- model_dollars()
    data.frame(month = md$month,
               predicted_bill = md$bill * personal_factor(),
               HDD = md$HDD, CDD = md$CDD, mean_temp = md$mean_temp)
  })
  climate_row <- reactive({ df <- climate_df(); df[df$month == input$month, ] })

  ## When someone personalizes, seed the costs tab with their own bill
  observeEvent(input$my_bill, {
    b <- input$my_bill
    if (!is.null(b) && !is.na(b) && b > 0) {
      updateNumericInput(session, "unpaid_bill", value = round(b))
      updateNumericInput(session, "dpa_balance", value = round(b))
    }
  }, ignoreInit = TRUE)

  observeEvent(input$shock_btn, {
    req(input$month)
    m <- input$month
    ## Sample one of the 20 most extreme stretches actually recorded in
    ## this calendar month since 1948 and replay it.
    ev_pool <- SHOCK_EVENTS[SHOCK_EVENTS$mo == match(m, month.abb), ]
    ev <- ev_pool[sample(nrow(ev_pool), 1), ]
    direction <- if (ev$anom > 0) "hotter" else "colder"
    shock$kind <- sprintf("%d-day %s like %s %d (%d degrees F %s than the month's average)",
                          ev$days, ev$kind, month.name[ev$mo], ev$year, abs(round(ev$anom)), direction)
    shock$active <- TRUE; shock$month <- m; shock$delta_temp <- ev$anom; shock$days <- ev$days
  })
  observeEvent(input$reset_btn, { shock$active <- FALSE })
  observeEvent(input$month, { shock$active <- FALSE })
  observeEvent(input$state, { shock$active <- FALSE })

  output$shock_active <- reactive({ shock$active })
  outputOptions(output, "shock_active", suspendWhenHidden = FALSE)
  output$shock_desc <- renderText({ req(shock$active); paste("Simulated:", shock$kind) })

  shocked_month_bill <- reactive({
    req(shock$active)
    df <- climate_df(); row <- df[df$month == shock$month, ]
    ## `shock$days` days of the month are replaced by a temperature anomaly
    ## (delta_temp) on top of that month's REAL average temperature -- not
    ## an offset from the 65F balance point, which would barely register
    ## in a month already averaging near it (e.g. August already averages
    ## 78.7F, so a heatwave has to be defined relative to that, not to 65F).
    ## The remaining days keep the month's normal per-day degree-days.
    shocked_temp <- row$mean_temp + shock$delta_temp
    shock_hdd_per_day <- max(BALANCE_POINT - shocked_temp, 0)
    shock_cdd_per_day <- max(shocked_temp - BALANCE_POINT, 0)
    remaining_frac <- (30 - shock$days) / 30
    normal_hdd <- row$HDD * remaining_frac; normal_cdd <- row$CDD * remaining_frac
    hdd_tot <- normal_hdd + shock_hdd_per_day * shock$days
    cdd_tot <- normal_cdd + shock_cdd_per_day * shock$days
    heat <- if (heat_on()) HEATING_RATE_PER_HDD * hdd_tot else 0
    (BASELOAD + heat + COOLING_RATE_PER_CDD * cdd_tot) * price_factor() * personal_factor()
  })

  ## One plain sentence that says what the chart shows, so nobody has to
  ## decode the chart to get the point.
  output$bill_headline <- renderUI({
    df <- climate_df()
    hi <- which.max(df$predicted_bill); lo <- which.min(df$predicted_bill)
    who <- if (identical(personal_factor(), 1)) "A typical home's" else "Your"
    p(class = "chart-headline",
      HTML(sprintf("%s biggest bill hits in %s, about %s. The cheapest month is %s, about %s.",
                   who, month.name[hi], B(sprintf("$%.0f", df$predicted_bill[hi])),
                   month.name[lo], B(sprintf("$%.0f", df$predicted_bill[lo])))))
  })

  ## Bars instead of a line: each month is its own bill, and a bar reads
  ## as "this much money" at a glance. The thin whisker on each bar is the
  ## real 10th-90th percentile range across the last 30 years. A weather event
  ## shows up as a red chunk stacked on top of that month's bar.
  output$bill_plot <- renderPlotly({
    k <- pc()
    df <- climate_df(); f <- personal_factor(); md <- model_dollars()
    base <- df$predicted_bill
    lo <- pmax(0, md$p10 * f); hi <- md$p90 * f
    sel_i <- match(input$month, month.abb)
    ev <- isTRUE(shock$active)
    ev_i <- if (ev) match(shock$month, month.abb) else NA
    d <- if (ev) shocked_month_bill() - base[ev_i] else 0
    bar_y <- base
    if (ev && d < 0) bar_y[ev_i] <- base[ev_i] + d

    cols <- ifelse(seq_len(12) == sel_i, k$accent, k$bar)
    hover <- sprintf("<b>%s</b><br>Expected bill: $%.0f<br>In 8 of 10 years: $%.0f to $%.0f",
                     month.name, base, lo, hi)

    p <- plot_ly(source = "bill_src") |>
      add_bars(x = month.abb, y = bar_y, marker = list(color = cols),
               text = hover, hoverinfo = "text", textposition = "none",
               name = "Expected bill", showlegend = FALSE)
    if (ev) {
      if (d >= 0) {
        p <- p |> add_bars(x = shock$month, y = d, marker = list(color = k$red),
                           text = sprintf("<b>%s with the event</b><br>About $%.0f extra", month.name[ev_i], d),
                           hoverinfo = "text", textposition = "none", showlegend = FALSE)
      } else {
        p <- p |> add_bars(x = shock$month, y = -d,
                           marker = list(color = "rgba(0,0,0,0)", line = list(color = k$good, width = 2)),
                           text = sprintf("<b>%s with the event</b><br>About $%.0f less", month.name[ev_i], -d),
                           hoverinfo = "text", textposition = "none", showlegend = FALSE)
      }
    }
    ## Whiskers ride on an invisible trace so they stay at the normal bill
    ## even when an event bar is stacked on top
    p <- p |> add_trace(type = "scatter", mode = "markers", x = month.abb, y = base,
                        marker = list(size = 1, color = "rgba(0,0,0,0)"),
                        error_y = list(type = "data", symmetric = FALSE, array = hi - base,
                                       arrayminus = base - lo, color = k$dim, thickness = 1.5, width = 5),
                        hoverinfo = "skip", showlegend = FALSE)

    ## Label the month being looked at, and the event if there is one
    top <- function(i) max(hi[i], bar_y[i] + if (ev && identical(i, ev_i)) abs(d) else 0)
    sel_txt <- sprintf("$%.0f", base[sel_i])
    if (ev && identical(sel_i, ev_i)) sel_txt <- sprintf("$%.0f %s $%.0f", base[sel_i], if (d >= 0) "+" else "-", abs(d))
    ann <- list(list(x = month.abb[sel_i], y = top(sel_i), text = paste0("<b>", sel_txt, "</b>"),
                     yanchor = "bottom", yshift = 3, showarrow = FALSE, font = list(color = k$ink, size = 14)))
    if (ev && !identical(sel_i, ev_i)) {
      ann[[2]] <- list(x = month.abb[ev_i], y = top(ev_i),
                       text = sprintf("%s$%.0f", if (d >= 0) "+" else "-", abs(d)),
                       yanchor = "bottom", yshift = 3, showarrow = FALSE, font = list(color = k$ink, size = 13))
    }

    p |> chart_layout(k = k, yaxis = list(title = "", tickprefix = "$", rangemode = "tozero", fixedrange = TRUE),
                      xaxis = list(title = "", categoryorder = "array", categoryarray = month.abb, fixedrange = TRUE, showgrid = FALSE),
                      barmode = "stack", bargap = 0.28, annotations = ann,
                      showlegend = FALSE, margin = list(t = 24, l = 50, r = 10)) |>
      event_register("plotly_click")
  })

  ## Click a month on the chart to focus it
  observeEvent(event_data("plotly_click", source = "bill_src"), {
    d <- event_data("plotly_click", source = "bill_src")
    m <- as.character(d$x[1])
    if (m %in% month.abb) updateSelectInput(session, "month", selected = m)
  })

  ## Live NYC temperature from Open-Meteo (free, no key). Fetched once per
  ## visit with a hard timeout; if the fetch fails for any reason the card
  ## simply doesn't appear and nothing else is affected.
  live_temp <- reactive({
    tryCatch({
      old <- getOption("timeout"); options(timeout = 5); on.exit(options(timeout = old), add = TRUE)
      r <- srow()
      u <- sprintf("https://api.open-meteo.com/v1/forecast?latitude=%.4f&longitude=%.4f&current=temperature_2m&temperature_unit=fahrenheit", r$lat, r$lon)
      txt <- paste(suppressWarnings(readLines(u, warn = FALSE)), collapse = "")
      m <- regmatches(txt, regexpr('temperature_2m"\\s*:\\s*-?[0-9.]+', txt))
      if (!length(m)) return(NULL)
      val <- as.numeric(sub('.*:', '', m))
      if (is.na(val) || val < -40 || val > 130) NULL else val
    }, error = function(e) NULL)
  })

  output$live_now <- renderUI({
    t <- live_temp()
    if (is.null(t)) return(NULL)
    cur_mo <- as.integer(format(Sys.Date(), "%m"))
    norm <- sclim()$mean_temp[cur_mo]
    mo_full <- month.name[cur_mo]
    diff <- t - norm
    diff_txt <- if (abs(diff) < 1) sprintf("right at the %s average", mo_full)
                else sprintf("%.0f degrees %s the %s average of %.0f F", abs(diff), if (diff > 0) "above" else "below", mo_full, norm)
    hdd_day <- max(BALANCE_POINT - t, 0); cdd_day <- max(t - BALANCE_POINT, 0)
    heat <- if (heat_on()) HEATING_RATE_PER_HDD * hdd_day * 30 else 0
    month_like_today <- (BASELOAD + heat + COOLING_RATE_PER_CDD * cdd_day * 30) * price_factor() * personal_factor()
    sheet(paste("Right now in", if (identical(input$state, "New York")) "New York" else srow()$city),
        p(style = "margin:0;",
          HTML(sprintf("It's <strong>%.0f F</strong> outside, %s. A whole month of days like today would run about <strong>$%.0f</strong>.",
                       t, diff_txt, month_like_today))),
        p(class = "fine-print", style = "margin:4px 0 0 0;", "Live reading from Open-Meteo, updated each time you open the page."))
  })

  output$bill_baseline <- renderText({ sprintf("$%.0f", climate_row()$predicted_bill) })
  output$bill_range <- renderText({
    f <- personal_factor()
    md <- model_dollars()[match(input$month, month.abb), ]
    mo_full <- month.name[match(input$month, month.abb)]
    sprintf("Over the last 30 years, %s's bill%s landed between $%.0f and $%.0f in 8 years out of 10.",
            mo_full, if (identical(f, 1)) "" else " for a home like yours",
            max(0, md$p10 * f), md$p90 * f)
  })
  output$bill_shocked <- renderText({
    sprintf("$%.0f", if (isTRUE(shock$active)) shocked_month_bill() else climate_row()$predicted_bill)
  })
  output$bill_delta <- renderText({
    if (isTRUE(shock$active)) {
      d <- shocked_month_bill() - climate_row()$predicted_bill
      sprintf("%s$%.0f", if (d >= 0) "+" else "-", abs(d))
    } else "$0"
  })

  current_bill <- reactive({
    if (isTRUE(shock$active) && shock$month == input$month) shocked_month_bill() else climate_row()$predicted_bill
  })



  ## ---- Budget jar: put the same amount away every month ----
  ## The set-aside is the average of the 12 estimated bills, so over a full
  ## year the jar ends where it started. The cushion is how much you'd need
  ## in the jar on day one so it never goes below zero.
  jar <- reactive({
    bills <- climate_df()$predicted_bill
    amt <- mean(bills)
    start <- match(if (is.null(input$jar_start)) "Jan" else input$jar_start, month.abb)
    cushion_for <- function(s) {
      idx <- ((s - 1 + 0:11) %% 12) + 1
      max(0, -min(cumsum(amt - bills[idx])))
    }
    idx <- ((start - 1 + 0:11) %% 12) + 1
    cushion <- cushion_for(start)
    all_cushions <- vapply(1:12, cushion_for, numeric(1))
    best <- which(all_cushions < 0.5)
    list(amt = amt, idx = idx, bills = bills[idx], cushion = cushion,
         balance = cushion + cumsum(amt - bills[idx]),
         best = if (length(best)) best[1] else which.min(all_cushions))
  })

  output$jar_amount <- renderText({ sprintf("$%.0f", jar()$amt) })

  output$jar_headline <- renderUI({
    j <- jar()
    start_name <- month.name[j$idx[1]]
    txt <- if (j$cushion < 0.5) {
      sprintf("Start in %s and the jar never runs dry. It fills up in the cheap months and covers the expensive ones. At its fullest it holds about %s.",
              start_name, B(sprintf("$%.0f", max(j$balance))))
    } else {
      sprintf("Start in %s and the jar runs short before the cheap months come back around. You'd need about %s in it on day one, or start in %s instead so the cheap months fill it first.",
              start_name, B(sprintf("$%.0f", j$cushion)), month.name[j$best])
    }
    p(class = "chart-headline", HTML(txt))
  })

  output$jar_plot <- renderPlotly({
    k <- pc(); j <- jar()
    labs <- month.abb[j$idx]
    drew <- j$bills > j$amt
    hover <- sprintf("<b>After paying %s's $%.0f bill</b><br>$%.0f left in the jar",
                     month.name[j$idx], j$bills, j$balance)
    plot_ly(x = factor(labs, levels = labs), y = j$balance, type = "bar",
            marker = list(color = ifelse(drew, k$amber, k$accent)),
            text = hover, hoverinfo = "text", textposition = "none") |>
      chart_layout(k = k, yaxis = list(title = "", tickprefix = "$", rangemode = "tozero", fixedrange = TRUE),
                   xaxis = list(title = "", fixedrange = TRUE, showgrid = FALSE),
                   bargap = 0.3, showlegend = FALSE, margin = list(t = 10, l = 50, r = 10))
  })

  ## ---- Is it getting more expensive? (trend fit in python/update_weather.py) ----
