## One month of the worked example on the bill page, computed from the
## same numbers the chart uses so it can never go stale
ledger_month <- function(m, top_margin = FALSE) {
  h <- HIST_MONTHLY[m, ]
  heat <- HEATING_RATE_PER_HDD * h$hdd_mean
  cool <- COOLING_RATE_PER_CDD * h$cdd_mean
  pts <- function(x) if (x < 0.5) "0 points" else paste(formatC(round(x), format = "d", big.mark = ","), "points")
  cents <- function(r) sprintf("at about %.0f cents", 100 * r)
  tagList(
    div(class = "how-month", style = if (top_margin) "margin-top:18px;" else NULL, month.name[m]),
    bill_line("Stuff that's always plugged in", sprintf("$%.0f", BASELOAD)),
    bill_line(if (heat < 0.5) "Heating: 0 points" else paste("Heating:", pts(h$hdd_mean), cents(HEATING_RATE_PER_HDD)), sprintf("$%.0f", heat)),
    bill_line(if (cool < 0.5) "Cooling: 0 points" else paste("Cooling:", pts(h$cdd_mean), cents(COOLING_RATE_PER_CDD)), sprintf("$%.0f", cool)),
    bill_line(paste(month.name[m], "bill"), sprintf("$%.0f", h$bill_mean), class = "total")
  )
}

