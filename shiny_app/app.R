## Weather: NOAA's official monthly heating and cooling degree days for the
## Central Park station, 1948 onward. python/update_weather.py downloads
## them, checks every month, and writes the three files in data/. Rerun it
## once a year and redeploy to keep the site current.
DD            <- read.csv("data/nyc_degree_days.csv")
TREND         <- read.csv("data/climate_trend.csv")
TREND_SUMMARY <- read.csv("data/climate_trend_summary.csv")
FIRST_YEAR    <- min(DD$year)
LAST_YEAR     <- max(DD$year)
N_YEARS       <- LAST_YEAR - FIRST_YEAR + 1

## "Normal" weather = the last 30 years, the same window length weather
## services use for their normals. Older summers were cooler and older
## winters colder, so averaging all the way back to 1948 would understate
## today's AC and overstate today's heat.
NORMAL_YEARS <- (LAST_YEAR - 29):LAST_YEAR
NORMAL       <- DD[DD$year %in% NORMAL_YEARS, ]

## Dollar scale. The June-September cooling cost of a normal summer is
## matched to NEADA's published 2026 Mid-Atlantic average summer cooling
## bill. The heating rate is a stated assumption (40% of the cooling rate),
## because most New York homes heat mostly with gas.
BASELOAD              <- 45
NEADA_SUMMER_COOLING  <- 790
HEAT_SHARE_OF_COOLING <- 0.40
BALANCE_POINT         <- 65
normal_summer_cdd     <- mean(tapply(NORMAL$cdd[NORMAL$month %in% 6:9],
                                     NORMAL$year[NORMAL$month %in% 6:9], sum))
COOLING_RATE_PER_CDD  <- NEADA_SUMMER_COOLING / normal_summer_cdd
HEATING_RATE_PER_HDD  <- HEAT_SHARE_OF_COOLING * COOLING_RATE_PER_CDD

predict_bill <- function(hdd, cdd) BASELOAD + HEATING_RATE_PER_HDD * hdd + COOLING_RATE_PER_CDD * cdd

## Per calendar month over the normal years: average bill, the 10th-90th
## percentile range of the 30 actual years, and average conditions.
HIST_MONTHLY <- do.call(rbind, lapply(1:12, function(m) {
  x <- NORMAL[NORMAL$month == m, ]
  b <- predict_bill(x$hdd, x$cdd)
  data.frame(bill_mean = mean(b),
             bill_p10  = unname(quantile(b, 0.10)),
             bill_p90  = unname(quantile(b, 0.90)),
             hdd_mean  = mean(x$hdd), cdd_mean = mean(x$cdd), mean_temp = mean(x$tavg))
}))
