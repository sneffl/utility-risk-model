## ---------------------------------------------------------------
## Server
## ---------------------------------------------------------------
server <- function(input, output, session) {

  ## ---- Welcome, once per visit ----
  showModal(modalDialog(
    title = "Welcome",
    p("This tool forecasts your electric bill from 68 years of real weather, shows what an unpaid bill leads to and when, and lists the help that actually exists."),
    p(strong("Start with one number:"), " enter your last electric bill in the left panel and everything here personalizes to your household."),
    footer = tagList(
      actionButton("welcome_help", "My power is at risk right now", class = "btn-danger"),
      modalButton("Got it")
    ),
    easyClose = TRUE
  ))
  observeEvent(input$welcome_help, {
    removeModal()
    nav_select("nav", "Get Help")
  })

  ## Urgent-risk banner button
  observeEvent(input$goto_help, { nav_select("nav", "Get Help") })

  ## ---- Bill Forecast tab ----
  shock <- reactiveValues(active = FALSE, month = NULL, delta_temp = 0, days = 0, kind = "")

  ## Outside factors: local electricity price (state average) and how the
  ## home is heated. Gas/oil heat means winter heating never touches the
  ## electric bill, so that whole component drops out.
  heat_on <- reactive({ !identical(input$heat_fuel, "other") })
  price_factor <- reactive({
    pr <- STATE_PRICES$price[STATE_PRICES$state == input$state]
    if (length(pr) == 0) 1 else pr / NY_PRICE
  })

  ## Model-household dollars per month under the current fuel + state,
  ## before personal scaling. The bill model is linear in degree-days, so
  ## dropping the heating component is exact; the 80% band is rescaled in
  ## proportion to each month's remaining bill.
  model_dollars <- reactive({
    heat <- if (heat_on()) HEATING_RATE_PER_HDD * HIST_MONTHLY$hdd_mean else 0
    base <- BASELOAD + heat + COOLING_RATE_PER_CDD * HIST_MONTHLY$cdd_mean
    ratio <- base / HIST_MONTHLY$bill_mean
    data.frame(month = HIST_MONTHLY$month,
               bill = base * price_factor(),
               p10  = HIST_MONTHLY$bill_p10 * ratio * price_factor(),
               p90  = HIST_MONTHLY$bill_p90 * ratio * price_factor(),
               HDD = HIST_MONTHLY$hdd_mean, CDD = HIST_MONTHLY$cdd_mean,
               mean_temp = HIST_MONTHLY$mean_temp)
  })

  output$state_note <- renderUI({
    if (identical(input$state, "New York")) return(NULL)
    pr <- STATE_PRICES$price[STATE_PRICES$state == input$state]
    div(class = "disclaimer",
        sprintf("Priced at %s's average residential rate, %.1f cents/kWh vs New York's %.1f (EIA, May 2026). The seasonal shape still follows New York's climate, so if your weather differs a lot, treat the pattern loosely.",
                input$state, pr, NY_PRICE))
  })

  ## Personal calibration: if the visitor enters their own last bill, the
  ## ratio of their bill to the adjusted model bill for that month rescales
  ## every dollar in the app. Clamped so one odd bill can't produce a
  ## nonsense forecast.
  personal_factor <- reactive({
    b <- input$my_bill
    if (is.null(b) || is.na(b) || b <= 0) return(1)
    ref <- model_dollars()$bill[match(input$my_bill_month, month.abb)]
    max(0.25, min(5, b / ref))
  })
  output$calib_note <- renderUI({
    f <- personal_factor()
    if (identical(f, 1)) return(NULL)
    pct <- round(100 * abs(f - 1))
    dir <- if (f >= 1) "above" else "below"
    div(class = "disclaimer",
        sprintf("Calibrated to your bill: your household runs about %d%% %s the model home for your state and heating type, and every number in the app now reflects that.", pct, dir))
  })

  ## The month's climate, scaled to the visitor's household.
  climate_df <- reactive({
    md <- model_dollars()
    data.frame(month = md$month,
               predicted_bill = md$bill * personal_factor(),
               HDD = md$HDD, CDD = md$CDD, mean_temp = md$mean_temp)
  })
  climate_row <- reactive({ df <- climate_df(); df[df$month == input$month, ] })

  ## When someone personalizes, seed the costs tab with their own bill
  observeEvent(input$my_bill, {
    b <- input$my_bill
    if (!is.null(b) && !is.na(b) && b > 0) {
      updateNumericInput(session, "unpaid_bill", value = round(b))
      updateNumericInput(session, "dpa_balance", value = round(b))
    }
  }, ignoreInit = TRUE)

  observeEvent(input$shock_btn, {
    req(input$month)
    m <- input$month
    ## Sample one of the 20 most extreme stretches actually recorded in
    ## this calendar month since 1948 and replay it.
    ev_pool <- SHOCK_EVENTS[SHOCK_EVENTS$mo == match(m, month.abb), ]
    ev <- ev_pool[sample(nrow(ev_pool), 1), ]
    direction <- if (ev$anom > 0) "hotter" else "colder"
    shock$kind <- sprintf("%d-day %s like %s %d (%d degrees F %s than the month's average)",
                          ev$days, ev$kind, month.name[ev$mo], ev$year, abs(round(ev$anom)), direction)
    shock$active <- TRUE; shock$month <- m; shock$delta_temp <- ev$anom; shock$days <- ev$days
  })
  observeEvent(input$reset_btn, { shock$active <- FALSE })
  observeEvent(input$month, { shock$active <- FALSE })

  output$shock_active <- reactive({ shock$active })
  outputOptions(output, "shock_active", suspendWhenHidden = FALSE)
  output$shock_desc <- renderText({ req(shock$active); paste("Simulated:", shock$kind) })

  shocked_month_bill <- reactive({
    req(shock$active)
    df <- climate_df(); row <- df[df$month == shock$month, ]
    ## `shock$days` days of the month are replaced by a temperature anomaly
    ## (delta_temp) on top of that month's REAL average temperature -- not
    ## an offset from the 65F balance point, which would barely register
    ## in a month already averaging near it (e.g. August already averages
    ## 78.7F, so a heatwave has to be defined relative to that, not to 65F).
    ## The remaining days keep the month's normal per-day degree-days.
    shocked_temp <- row$mean_temp + shock$delta_temp
    shock_hdd_per_day <- max(BALANCE_POINT - shocked_temp, 0)
    shock_cdd_per_day <- max(shocked_temp - BALANCE_POINT, 0)
    remaining_frac <- (30 - shock$days) / 30
    normal_hdd <- row$HDD * remaining_frac; normal_cdd <- row$CDD * remaining_frac
    hdd_tot <- normal_hdd + shock_hdd_per_day * shock$days
    cdd_tot <- normal_cdd + shock_cdd_per_day * shock$days
    heat <- if (heat_on()) HEATING_RATE_PER_HDD * hdd_tot else 0
    (BASELOAD + heat + COOLING_RATE_PER_CDD * cdd_tot) * price_factor() * personal_factor()
  })

  output$bill_plot <- renderPlotly({
    df <- climate_df()
    f <- personal_factor()
    sel <- df[df$month == input$month, ]
    p <- plot_ly(df, x = ~month, source = "bill_src")
    ## Shaded band: where 80% of the last 68 years actually landed
    md <- model_dollars()
    p <- p |>
      add_trace(y = md$p90 * f, type = "scatter", mode = "lines",
                line = list(width = 0), showlegend = FALSE, hoverinfo = "skip") |>
      add_trace(y = md$p10 * f, type = "scatter", mode = "lines",
                line = list(width = 0), fill = "tonexty", fillcolor = "rgba(255,210,31,0.14)",
                name = "Range of real years", hovertemplate = "%{x} range<extra></extra>") |>
      add_trace(y = ~predicted_bill, type = "scatter", mode = "lines+markers",
                line = list(color = VOLT, width = 3), marker = list(color = VOLT, size = 8),
                name = if (identical(f, 1)) "Typical home" else "Your home (estimated)",
                hovertemplate = "%{x}: $%{y:.2f}<extra></extra>") |>
      ## Ring around the month being looked at
      add_markers(x = sel$month, y = sel$predicted_bill,
                  marker = list(color = "rgba(0,0,0,0)", size = 16,
                                line = list(color = INK, width = 2)),
                  showlegend = FALSE, hoverinfo = "skip")
    if (isTRUE(shock$active)) {
      p <- p |> add_markers(x = shock$month, y = shocked_month_bill(), marker = list(color = RED, size = 14, symbol = "diamond"),
                             name = "With the event", hovertemplate = paste0(shock$month, " + event: $%{y:.2f}<extra></extra>"))
    }
    p |> chart_layout(yaxis = list(title = "Predicted monthly bill ($)", tickprefix = "$"), xaxis = list(title = "", categoryorder = "array", categoryarray = month.abb),
                legend = list(orientation = "h", y = 1.15), margin = list(t = 10)) |>
      event_register("plotly_click")
  })

  ## Click a month on the chart to focus it
  observeEvent(event_data("plotly_click", source = "bill_src"), {
    d <- event_data("plotly_click", source = "bill_src")
    m <- as.character(d$x[1])
    if (m %in% month.abb) updateSelectInput(session, "month", selected = m)
  })

  ## Live NYC temperature from Open-Meteo (free, no key). Fetched once per
  ## visit with a hard timeout; if the fetch fails for any reason the card
  ## simply doesn't appear and nothing else is affected.
  live_temp <- reactive({
    tryCatch({
      old <- getOption("timeout"); options(timeout = 5); on.exit(options(timeout = old), add = TRUE)
      u <- "https://api.open-meteo.com/v1/forecast?latitude=40.7128&longitude=-74.006&current=temperature_2m&temperature_unit=fahrenheit"
      txt <- paste(suppressWarnings(readLines(u, warn = FALSE)), collapse = "")
      m <- regmatches(txt, regexpr('temperature_2m"\\s*:\\s*-?[0-9.]+', txt))
      if (!length(m)) return(NULL)
      val <- as.numeric(sub('.*:', '', m))
      if (is.na(val) || val < -40 || val > 130) NULL else val
    }, error = function(e) NULL)
  })

  output$live_now <- renderUI({
    t <- live_temp()
    if (is.null(t)) return(NULL)
    cur_mo <- as.integer(format(Sys.Date(), "%m"))
    norm <- HIST_MONTHLY$mean_temp[cur_mo]
    mo_full <- month.name[cur_mo]
    diff <- t - norm
    diff_txt <- if (abs(diff) < 1) sprintf("right at the %s average", mo_full)
                else sprintf("%.0f degrees %s the %s average of %.0f F", abs(diff), if (diff > 0) "above" else "below", mo_full, norm)
    hdd_day <- max(BALANCE_POINT - t, 0); cdd_day <- max(t - BALANCE_POINT, 0)
    heat <- if (heat_on()) HEATING_RATE_PER_HDD * hdd_day * 30 else 0
    month_like_today <- (BASELOAD + heat + COOLING_RATE_PER_CDD * cdd_day * 30) * price_factor() * personal_factor()
    div(class = "stat-box", style = "text-align:left; margin-top:12px;",
        HTML(sprintf("<strong>Right now in NYC: %.0f F</strong>, %s. A whole month of days like today would run about <strong>$%.0f</strong>. Live reading from Open-Meteo.",
                     t, diff_txt, month_like_today)))
  })

  output$bill_baseline <- renderText({ sprintf("$%.2f", climate_row()$predicted_bill) })
  output$bill_range <- renderText({
    f <- personal_factor()
    md <- model_dollars()[match(input$month, month.abb), ]
    mo_full <- month.name[match(input$month, month.abb)]
    if (identical(f, 1)) {
      sprintf("Prediction interval: based on 68 years of weather, %s lands between $%.0f and $%.0f in 8 years out of 10.",
              mo_full, md$p10, md$p90)
    } else {
      sprintf("Prediction interval for your household: based on 68 years of weather, expect %s to land between $%.0f and $%.0f in 8 years out of 10.",
              mo_full, md$p10 * f, md$p90 * f)
    }
  })
  output$bill_shocked <- renderText({
    if (isTRUE(shock$active)) sprintf("$%.2f", shocked_month_bill()) else "-"
  })
  output$bill_delta <- renderText({
    if (isTRUE(shock$active)) {
      d <- shocked_month_bill() - climate_row()$predicted_bill
      sprintf("%s$%.2f", if (d >= 0) "+" else "-", abs(d))
    } else "-"
  })

  current_bill <- reactive({
    if (isTRUE(shock$active) && shock$month == input$month) shocked_month_bill() else climate_row()$predicted_bill
  })

  ## ---- Risk & Disconnection Timeline tab ----
  output$tier_desc <- renderUI({
    div(class = "disclaimer", TIER_DESCRIPTIONS[[input$tier]])
  })

  stress_index <- reactive({ req(input$income > 0); current_bill() / input$income })

  chain_analysis <- reactive({
    P <- build_transition_matrix(input$tier, stress_index())
    list(P = P, a = analyze_chain(P))
  })

  output$stress_index <- renderText({ sprintf("%.1f%%", 100 * stress_index()) })
  output$exp_months <- renderText({
    em <- chain_analysis()$a$expected_months
    if (em > 240) "20+ yrs" else if (em > 24) sprintf("%.0f yrs", em / 12) else sprintf("%.0f mo", em)
  })
  output$p12 <- renderText({ sprintf("%.1f%%", 100 * chain_analysis()$a$p12) })

  ## Plain-language verdict at the top of the tab
  output$risk_verdict <- renderUI({
    a <- chain_analysis()$a
    p12 <- a$p12
    bill <- current_bill()
    at12 <- a$trajectory["12", ]
    best_state <- names(which.max(at12))
    best_label <- c(Current = "Current (paid up)", Late = "Late",
                    Severe = "Severely late", Disconnected = "Disconnected")[[best_state]]
    chance <- if (p12 < 0.005) "under 0.5% (less than 1 in 200)"
              else sprintf("%.1f%% (about 1 in %d)", 100 * p12, max(2, round(1 / p12)))
    tone <- if (p12 < 0.02) {
      "That's a low-risk picture. Staying current is by far the most likely outcome."
    } else if (p12 < 0.15) {
      "Most likely you stay current, but the risk is real enough to be worth a plan."
    } else {
      "That's a high-risk picture. The Get Help tab lists concrete steps that change these odds, starting with a payment agreement."
    }
    mo_full <- month.name[match(input$month, month.abb)]
    article <- if (grepl("^[AEIOU]", mo_full)) "an" else "a"
    dpa_note <- if (isTRUE(input$has_dpa)) {
      p(style = "margin-bottom:0; color:#3ecf8e;",
        HTML(paste0(B("You have a payment agreement."), " While you keep up its payments, the disconnection clock is legally paused, so the numbers below describe what would happen without the agreement (or if it lapses). Keeping the DPA current is what holds them at bay.")))
    } else NULL
    urgent <- if (p12 >= 0.15 && !isTRUE(input$has_dpa)) {
      div(class = "alert-urgent",
        p(style = "margin-bottom:4px;", strong("If a shutoff notice is in your hand, act today.")),
        p(style = "margin-bottom:4px;",
          HTML(paste0("Two moves change everything: call the number on your bill and ask for a ",
                      B("deferred payment agreement"),
                      " (signing one stops the disconnection clock), and if service is about to be cut, call the state's emergency line at ",
                      B("1-800-342-3355"), "."))),
        actionButton("goto_help", "See everything that can help", class = "btn-danger btn-sm")
      )
    } else NULL
    tagList(
      urgent,
      h4("What this means for you", style = "margin-bottom:8px;"),
      p(style = "font-size:16px; margin-bottom:4px;",
        HTML(sprintf("With %s %s bill of %s and monthly income of %s, the model's estimated probability of disconnection within one year is %s.",
                     article, mo_full, B(sprintf("$%.0f", bill)), B(sprintf("$%s", formatC(input$income, format = "d", big.mark = ","))), B(chance)))),
      p(style = "margin-bottom:4px;",
        HTML(sprintf("Most likely status a year from now: %s.", B(sprintf("%s, %.0f%%", best_label, 100 * max(at12)))))),
      p(class = "text-muted", style = "margin-bottom:6px;", tone),
      dpa_note,
      p(class = "text-muted", style = "font-size:12px; margin-top:10px; margin-bottom:0;",
        "This is a statistical estimate from historical patterns and stated assumptions, described on the About tab. It is not a prediction of what your utility will actually decide about any individual account.")
    )
  })

  output$markov_plot <- renderPlotly({
    traj <- chain_analysis()$a$trajectory
    df <- data.frame(month = as.integer(rownames(traj)), traj, check.names = FALSE)
    df$Behind <- df$Late + df$Severe
    n <- nrow(df)
    plot_ly(df, x = ~month) |>
      add_trace(y = ~Current, name = "Paid up", type = "scatter", mode = "lines",
                line = list(color = GOOD, width = 3),
                hovertemplate = "Month %{x}: %{y:.0%} chance you're paid up<extra></extra>") |>
      add_trace(y = ~Behind, name = "Behind on the bill", type = "scatter", mode = "lines",
                line = list(color = AMBER, width = 3),
                hovertemplate = "Month %{x}: %{y:.0%} chance you're behind<extra></extra>") |>
      add_trace(y = ~Disconnected, name = "Disconnected", type = "scatter", mode = "lines",
                line = list(color = RED, width = 3),
                hovertemplate = "Month %{x}: %{y:.0%} chance of disconnection<extra></extra>") |>
      add_annotations(x = df$month[n], y = c(df$Current[n], df$Behind[n], df$Disconnected[n]),
                      text = sprintf("%.0f%%", 100 * c(df$Current[n], df$Behind[n], df$Disconnected[n])),
                      xanchor = "left", showarrow = FALSE,
                      font = list(color = c(GOOD, AMBER, RED), size = 13)) |>
      chart_layout(yaxis = list(title = "Probability", tickformat = ".0%", rangemode = "tozero"),
             xaxis = list(title = "Months from now"),
             hovermode = "x unified",
             legend = list(orientation = "h", y = 1.12), margin = list(t = 10, r = 45))
  })

  output$markov_table <- renderDT({
    P <- round(chain_analysis()$P, 3)
    datatable(P, options = list(dom = "t", ordering = FALSE), class = "compact")
  })

  ## ---- Late Fee & Credit Impact tab ----
  output$fee_plot <- renderPlotly({
    df <- project_late_fees(input$unpaid_bill, 12)
    end_bal <- df$balance[nrow(df)]
    plot_ly(df, x = ~month, y = ~balance, type = "scatter", mode = "lines+markers",
            line = list(color = VOLT, width = 3), fill = "tozeroy", fillcolor = "rgba(255,210,31,0.10)",
            hovertemplate = "After %{x} months: $%{y:.2f}<extra></extra>") |>
      add_annotations(x = 12, y = end_bal, xanchor = "right", yanchor = "bottom", showarrow = FALSE,
                      text = sprintf("a year later: $%.0f (+$%.0f in fees)", end_bal, end_bal - input$unpaid_bill),
                      font = list(color = INK, size = 13)) |>
      chart_layout(yaxis = list(title = "Balance owed ($)", tickprefix = "$"), xaxis = list(title = "Months unpaid"), margin = list(t = 10))
  })

  credit_calc <- reactive({
    tier_now <- score_to_tier(input$credit_score)
    drop_range <- collection_point_drop_range(input$credit_score)
    drop <- mean(drop_range)
    new_score <- max(300, input$credit_score - drop)
    tier_after <- score_to_tier(new_score)
    apr_now <- tier_now[[input$car_type]]
    apr_after <- tier_after[[input$car_type]]
    pay_now <- monthly_payment(input$loan_amount, apr_now, input$loan_term)
    pay_after <- monthly_payment(input$loan_amount, apr_after, input$loan_term)
    list(tier_now = tier_now$tier, tier_after = tier_after$tier, apr_now = apr_now, apr_after = apr_after,
         total_now = pay_now * input$loan_term, total_after = pay_after * input$loan_term,
         drop_range = drop_range, new_score = new_score)
  })

  output$credit_explainer <- renderUI({
    cc <- credit_calc()
    p(sprintf("A collections mark commonly drops a score in the %d-%d point range (bigger hits for higher starting scores). Starting at %d (%s), that could land you around %d (%s).",
              cc$drop_range[1], cc$drop_range[2], input$credit_score, cc$tier_now, round(cc$new_score), cc$tier_after))
  })
  output$apr_before <- renderText({ sprintf("%.2f%%", credit_calc()$apr_now) })
  output$apr_after  <- renderText({ sprintf("%.2f%%", credit_calc()$apr_after) })
  output$extra_cost <- renderText({ sprintf("$%s", formatC(round(credit_calc()$total_after - credit_calc()$total_now), format = "d", big.mark = ",")) })

  ## ---- Shutoff cost panel ----
  AVG_MONTHLY_BILL <- mean(HIST_MONTHLY$bill_mean)
  shutoff_calc <- reactive({
    balance <- input$unpaid_bill * (1.015 ^ input$months_unpaid)
    deposit_cap <- 2 * AVG_MONTHLY_BILL
    list(balance = balance, deposit_cap = deposit_cap,
         lo = balance + 20, hi = balance + 150 + deposit_cap)
  })
  output$shutoff_balance <- renderText({ sprintf("$%.0f", shutoff_calc()$balance) })
  output$shutoff_deposit <- renderText({ sprintf("$%.0f", shutoff_calc()$deposit_cap) })
  output$shutoff_total <- renderUI({
    sc <- shutoff_calc()
    p(style = "font-size:16px; margin-bottom:0;",
      HTML(sprintf("All in, restoring service after a shutoff could take %s to %s, depending on your utility's fee and whether a deposit is required.",
                   B(sprintf("$%.0f", sc$lo)), B(sprintf("$%.0f", sc$hi)))))
  })

  ## ---- Get Help tab: HEFPA payment-agreement request letter ----
  letter_text <- reactive({
    bal <- input$dpa_balance
    if (is.null(bal) || is.na(bal) || bal <= 0) bal <- 0
    afford <- input$dpa_afford
    monthly <- if (!is.null(afford) && !is.na(afford) && afford >= 10) round(afford) else max(10, round(bal / 12))
    paste0(
format(Sys.Date(), "%B %d, %Y"), "\n\n",
"To: [Your utility company], Customer Assistance\n",
"Re: Account number [your account number]\n",
"Service address: [your address]\n\n",
"To whom it may concern,\n\n",
"I am a residential customer and my account carries an unpaid balance of about $", formatC(round(bal), format = "d", big.mark = ","), ". ",
"I am writing to request a deferred payment agreement under New York's Home Energy Fair Practices Act (Public Service Law and 16 NYCRR Part 11).\n\n",
"Based on my current finances, I can pay $", monthly, " per month toward the balance, in addition to my current monthly bills. ",
"I understand HEFPA requires payment agreement terms to reflect a customer's financial circumstances, and that agreements as low as no money down and ten dollars per month are available to customers who cannot afford more.\n\n",
"Please send me a written agreement to sign, and please hold any pending disconnection while this request is processed. ",
"If my account qualifies for assistance programs such as HEAP or an energy affordability discount, please tell me how to apply.\n\n",
"You can reach me at [your phone number or email].\n\n",
"Sincerely,\n",
"[Your name]\n")
  })
  output$letter_preview <- renderUI({
    tags$textarea(letter_text(), readonly = "readonly", rows = 14,
                  style = "width:100%; background:#17181c; color:#ecebe4; border:1px solid #2e3138; border-radius:6px; padding:12px; font-family:'IBM Plex Mono', monospace; font-size:13px; margin-bottom:10px;")
  })
  output$dl_letter <- downloadHandler(
    filename = function() "payment-agreement-request.txt",
    content = function(file) writeLines(letter_text(), file)
  )

  ## ---- Get Help tab: DPA payment plan calculator ----
  dpa_monthly <- function(months) {
    req(input$dpa_balance)
    max(input$dpa_balance / months, 10)  # HEFPA floor: installments can be as low as $10/month
  }
  output$dpa6  <- renderText({ sprintf("$%.0f", dpa_monthly(6)) })
  output$dpa12 <- renderText({ sprintf("$%.0f", dpa_monthly(12)) })
  output$dpa24 <- renderText({ sprintf("$%.0f", dpa_monthly(24)) })
}

