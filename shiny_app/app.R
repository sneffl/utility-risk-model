## ML risk tiers -- from the fitted logistic model's own Youden-optimal
## operating threshold (0.493) on real SGCC data; see report Section 4.
TIER_BASE_SLIP <- c(Low = 0.03, Elevated = 0.12, High = 0.28)
TIER_DESCRIPTIONS <- c(
  Low      = "You've generally paid on time, and your usage doesn't swing wildly month to month.",
  Elevated = "You've had one or two late payments, or your usage/income has been inconsistent lately.",
  High     = "You've missed multiple payments recently, received a notice, or your bill regularly strains your budget."
