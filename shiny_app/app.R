## Show one string in whichever language is picked. Both versions are on
## the page and the browser shows one, so switching is instant and nothing
## you typed gets reset.
tr <- function(key, inline = FALSE) {
  box <- if (inline) span else div
  ## Same attributes shiny's conditionalPanel uses, so this also works on
  ## inline spans (conditionalPanel itself only makes divs)
  only_if <- function(cond, x) box(`data-display-if` = cond, `data-ns-prefix` = "", x)
  tagList(only_if("input.help_lang != 'es'", HTML(HELP_TEXT$en[[key]])),
          only_if("input.help_lang == 'es'", HTML(HELP_TEXT$es[[key]])))
}
tr_over <- function(i) {
  tagList(span(`data-display-if` = "input.help_lang != 'es'", `data-ns-prefix` = "", HELP_TEXT$en$over[i]),
          span(`data-display-if` = "input.help_lang == 'es'", `data-ns-prefix` = "", HELP_TEXT$es$over[i]))
}

