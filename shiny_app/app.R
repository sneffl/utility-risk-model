  ## Probabilities -> whole households out of 100 that still sum to 100
  ## (largest-remainder rounding). People read "6 out of 100" much more
  ## accurately than "5.8%".
  out_of_100 <- function(p) {
    x <- 100 * p / sum(p); f <- floor(x); r <- 100 - sum(f)
    if (r > 0) { i <- order(x - f, decreasing = TRUE)[seq_len(r)]; f[i] <- f[i] + 1 }
    f
  }
