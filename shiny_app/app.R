    s <- TREND_SUMMARY[TREND_SUMMARY$season == "summer_cooling", ]
    w <- TREND_SUMMARY[TREND_SUMMARY$season == "winter_heating", ]
    scale <- price_factor() * personal_factor()
    list(s = s, w = w, scale = scale,
         summer_extra = (s$trend_end - s$trend_start) * COOLING_RATE_PER_CDD * scale,
         winter_saved = (w$trend_start - w$trend_end) * HEATING_RATE_PER_HDD * scale)
  })

  output$trend_headline <- renderUI({
    ti <- trend_info()
    who <- if (identical(personal_factor(), 1)) "a typical home" else "a home like yours"
