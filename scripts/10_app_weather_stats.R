## ============================================================
## 10_app_weather_stats.R
## Precompute the small weather tables the Shiny app embeds:
##   1. All-years (1948-2015) monthly bill forecast: mean and a
##      p10-p90 range, from each year's actual HDD/CDD totals.
##   2. Real historical extreme events per month: for each year,
##      the hottest and coldest 3/5/7-day stretch relative to that
##      month's long-run average temperature. The app's shock
##      button samples from the top 10 real events per month.
## Output: R code printed to output/app_weather_tables.R for
## pasting into shiny_app/app.R (keeps the app single-file).
## ============================================================

suppressPackageStartupMessages(library(data.table))

w <- fread("data/weather/nyc_weather_raw.csv")
w <- w[, .(date = as.IDate(Date), temp = as.numeric(Mean.TemperatureF))]
w <- w[!is.na(temp)]
w[, `:=`(yr = year(date), mo = month(date))]

BAL <- 65
BASELOAD <- 45; CRATE <- 0.600304; HRATE <- 0.240122
bill_from <- function(hdd, cdd) BASELOAD + HRATE * hdd + CRATE * cdd

## ---- 1. Per year x month HDD/CDD totals -> bill distribution ----
ym <- w[, .(hdd = sum(pmax(BAL - temp, 0)), cdd = sum(pmax(temp - BAL, 0)),
            mean_temp = mean(temp), ndays = .N), by = .(yr, mo)]
ym <- ym[ndays >= 25]                      # only reasonably complete months
ym[, bill := bill_from(hdd, cdd)]

monthly_all <- ym[, .(
  bill_mean = mean(bill), bill_p10 = quantile(bill, 0.10), bill_p90 = quantile(bill, 0.90),
  hdd_mean = mean(hdd), cdd_mean = mean(cdd), mean_temp = mean(mean_temp),
  n_years = .N), by = mo][order(mo)]

cat("Years of data per month:", paste(range(monthly_all$n_years), collapse = "-"), "\n")

## ---- 2. Real extreme events: best k-day anomaly per year x month ----
mo_avg <- ym[, .(mo_temp = mean(mean_temp)), by = mo]

events <- list()
for (m in 1:12) {
  base_temp <- mo_avg[mo == m, mo_temp]
  for (y in unique(ym[mo == m, yr])) {
    d <- w[yr == y & mo == m][order(date)]
    if (nrow(d) < 25) next
    best_hot <- best_cold <- NULL
    for (k in c(3, 5, 7)) {
      if (nrow(d) < k) next
      ra <- frollmean(d$temp, k, align = "left")
      hot_i <- which.max(ra); cold_i <- which.min(ra)
      hot <- ra[hot_i] - base_temp; cold <- ra[cold_i] - base_temp
      if (is.null(best_hot)  || hot  > best_hot$anom)  best_hot  <- list(k = k, anom = hot)
      if (is.null(best_cold) || cold < best_cold$anom) best_cold <- list(k = k, anom = cold)
    }
    events[[length(events) + 1]] <- data.table(
      mo = m, yr = y,
      hot_days = best_hot$k,  hot_anom = best_hot$anom,
      cold_days = best_cold$k, cold_anom = best_cold$anom)
  }
}
events <- rbindlist(events)

## Top 10 real hot and cold events per month (must actually be anomalous)
top_hot  <- events[hot_anom  >  2][order(mo, -hot_anom),  head(.SD, 10), by = mo,
                                    .SDcols = c("yr", "hot_days", "hot_anom")]
top_cold <- events[cold_anom < -2][order(mo,  cold_anom), head(.SD, 10), by = mo,
                                    .SDcols = c("yr", "cold_days", "cold_anom")]
setnames(top_hot,  c("yr", "hot_days", "hot_anom"),  c("year", "days", "anom"))
setnames(top_cold, c("yr", "cold_days", "cold_anom"), c("year", "days", "anom"))
top_hot[, kind := "heatwave"]; top_cold[, kind := "cold snap"]
shock_events <- rbind(top_hot, top_cold)[order(mo, kind, -abs(anom))]
shock_events[, anom := round(anom, 1)]

## ---- 3. Emit compact R code for the app ----
fmt <- function(x, d = 2) formatC(round(x, d), format = "f", digits = d)
out <- file("output/app_weather_tables.R", "w")
cat("## Generated by scripts/10_app_weather_stats.R from 1948-2015 NYC daily history\n", file = out)
cat("HIST_MONTHLY <- data.frame(\n", file = out)
cat("  month = factor(month.abb, levels = month.abb),\n", file = out)
cat(sprintf("  bill_mean = c(%s),\n", paste(fmt(monthly_all$bill_mean), collapse = ", ")), file = out)
cat(sprintf("  bill_p10  = c(%s),\n", paste(fmt(monthly_all$bill_p10),  collapse = ", ")), file = out)
cat(sprintf("  bill_p90  = c(%s),\n", paste(fmt(monthly_all$bill_p90),  collapse = ", ")), file = out)
cat(sprintf("  hdd_mean  = c(%s),\n", paste(fmt(monthly_all$hdd_mean, 1), collapse = ", ")), file = out)
cat(sprintf("  cdd_mean  = c(%s),\n", paste(fmt(monthly_all$cdd_mean, 1), collapse = ", ")), file = out)
cat(sprintf("  mean_temp = c(%s)\n",  paste(fmt(monthly_all$mean_temp, 1), collapse = ", ")), file = out)
cat(")\n\n", file = out)
cat("SHOCK_EVENTS <- data.frame(\n", file = out)
cat(sprintf("  mo   = c(%s),\n",  paste(shock_events$mo, collapse = ", ")), file = out)
cat(sprintf("  year = c(%s),\n",  paste(shock_events$year, collapse = ", ")), file = out)
cat(sprintf("  days = c(%s),\n",  paste(shock_events$days, collapse = ", ")), file = out)
cat(sprintf("  anom = c(%s),\n",  paste(shock_events$anom, collapse = ", ")), file = out)
cat(sprintf('  kind = c(%s)\n',   paste(sprintf('"%s"', shock_events$kind), collapse = ", ")), file = out)
cat(")\n", file = out)
close(out)

cat("Wrote output/app_weather_tables.R:", nrow(shock_events), "real events,",
    nrow(monthly_all), "monthly rows\n")
print(monthly_all[, .(mo, bill_mean = round(bill_mean), bill_p10 = round(bill_p10), bill_p90 = round(bill_p90))])
cat("\nSample real events (August):\n")
print(shock_events[mo == 8][1:6])
